"""Validate and minify the parameter description JSON for embedding into firmware.

Writes the minified JSON and a C header with the number of described parameters,
so the firmware can check at build time that it matches the parameter table.
"""

import argparse
import json
import sys


def fail(msg):
    sys.exit(f"{args.input}: error: {msg}")


parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--input", required=True)
parser.add_argument("--output-json", required=True)
parser.add_argument("--output-header", required=True)
args = parser.parse_args()

try:
    with open(args.input, encoding="utf-8") as f:
        desc = json.load(f)
except (OSError, json.JSONDecodeError) as e:
    fail(str(e))

params = desc.get("parameters") if isinstance(desc, dict) else None
if not isinstance(params, list) or not params:
    fail('"parameters" must be a non-empty array')

for index, p in enumerate(params):
    if not isinstance(p, dict):
        fail(f"parameter at index {index} must be an object")
    if p.get("id") != index:
        fail(f'parameter at index {index} must have "id": {index}')
    if not isinstance(p.get("name"), str) or not p["name"]:
        fail(f'parameter {index} must have a non-empty "name"')
    for key in ("readOnly", "persistent", "hidden", "live"):
        if key in p and not isinstance(p[key], bool):
            fail(f'parameter {index}: "{key}" must be a boolean')

minified = json.dumps(desc, separators=(",", ":"), ensure_ascii=False).encode("utf-8")
if len(minified) > 0xFFFF:
    fail(f"minified JSON is too large ({len(minified)} bytes, max 65535)")

with open(args.output_json, "wb") as f:
    f.write(minified)

with open(args.output_header, "w", encoding="utf-8") as f:
    f.write("/* Generated by scripts/gen_params_desc.py, do not edit. */\n")
    f.write("#ifndef PARAMS_DESC_GEN_H_\n#define PARAMS_DESC_GEN_H_\n\n")
    f.write(f"#define PARAMS_DESC_COUNT {len(params)}\n\n")
    f.write("#endif /* PARAMS_DESC_GEN_H_ */\n")
