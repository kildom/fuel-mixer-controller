namespace {

constexpr std::array<int32_t, PARAM_COUNT> default_parameters = {
	0,   // PARAM_NEXT_READ
	120, // PARAM_MINIMALNY_CZAS_PRACY: 2 minutes
	100, // PARAM_PROPORCJA_ROZPALKI
	30,  // PARAM_PROPORCJA_PALIWA_1
	70,  // PARAM_PROPORCJA_PALIWA_2
	15,  // PARAM_CZAS_ROZPALANIA: minutes
	15,  // PARAM_CZAS_WYKRYCIA_NASYPU_ROZPALKI: seconds
	5,   // PARAM_CZAS_WYKRYCIA_WYGASZENIA: minutes
	5,   // PARAM_MAKSYMALNY_CZAS_PRZEDLUZENIA_SYGNALU: seconds
	45,  // PARAM_CZAS_PRACY_POMPY: minutes
	0,   // PARAM_WYMUSZONA_PRACA
};

struct Signal {
	std::string name;
	std::string id;
	unsigned width;
};

std::array<bool, IO_INPUT_COUNT> input_values{};
std::array<bool, IO_OUTPUT_COUNT> output_values{};
std::array<bool, IO_OUTPUT_COUNT> recorded_output_values{};
std::array<int32_t, PARAM_COUNT> parameter_values = default_parameters;
std::array<Signal, IO_INPUT_COUNT + IO_OUTPUT_COUNT + PARAM_COUNT> signals;
std::ofstream vcd;
int current_time = 0;
int last_vcd_time = 0;

std::string signal_id(std::size_t index)
{
	return std::string(1, static_cast<char>('!' + index));
}

void write_time(int time)
{
	if (time < last_vcd_time) {
		throw std::runtime_error("VCD time moved backwards");
	}
	if (time != last_vcd_time) {
		vcd << '#' << time << '\n';
		last_vcd_time = time;
	}
}

void write_scalar(std::size_t index, bool value, int time)
{
	write_time(time);
	vcd << (value ? '1' : '0') << signals[index].id << '\n';
}

void write_parameter(std::size_t index, int32_t value, int time)
{
	write_time(time);
	vcd << 'b';
	const uint32_t bits = static_cast<uint32_t>(value);
	for (int bit = 31; bit >= 0; --bit) {
		vcd << ((bits >> bit) & 1U);
	}
	vcd << ' ' << signals[index].id << '\n';
}

void initialize_vcd(const char *filename)
{
	vcd.open(filename);
	if (!vcd) {
		throw std::runtime_error(std::string("cannot open VCD file: ") + filename);
	}

	std::size_t index = 0;
	const std::array<const char *, IO_INPUT_COUNT> input_names = {"loader", "sensor"};
	for (int i = 0; i < IO_INPUT_COUNT; ++i, ++index) {
		signals[index] = {input_names[i], signal_id(index), 1};
	}

	const std::array<const char *, IO_OUTPUT_COUNT> output_names = {
		"motor_1", "motor_2", "pump", "heater"
	};
	for (int i = 0; i < IO_OUTPUT_COUNT; ++i, ++index) {
		signals[index] = {output_names[i], signal_id(index), 1};
	}

	const std::array<const char *, PARAM_COUNT> parameter_names = {
		"next_read",
		"minimalny_czas_pracy",
		"proporcja_rozpalki",
		"proporcja_paliwa_1",
		"proporcja_paliwa_2",
		"czas_rozpalania",
		"czas_wykrycia_nasypu_rozpalki",
		"czas_wykrycia_wygaszenia",
		"maksymalny_czas_przedluzenia_sygnalu",
		"czas_pracy_pompy",
		"wymuszona_praca",
		"podglad_stanu"
	};
	for (int i = 0; i < PARAM_COUNT; ++i, ++index) {
		signals[index] = {parameter_names[i], signal_id(index), 32};
	}

	vcd << "$date generated by host logic tests $end\n"
	    << "$version ble_relays logic test harness $end\n"
	    << "$timescale 100ms $end\n"
	    << "$scope module controller $end\n";
	for (const auto &signal : signals) {
		vcd << "$var wire " << signal.width << ' ' << signal.id << ' '
		    << signal.name << " $end\n";
	}
	vcd << "$upscope $end\n$enddefinitions $end\n#0\n$dumpvars\n";

	index = 0;
	for (bool value : input_values) {
		vcd << (value ? '1' : '0') << signals[index++].id << '\n';
	}
	for (bool value : output_values) {
		vcd << (value ? '1' : '0') << signals[index++].id << '\n';
	}
	for (int32_t value : parameter_values) {
		vcd << 'b';
		const uint32_t bits = static_cast<uint32_t>(value);
		for (int bit = 31; bit >= 0; --bit) {
			vcd << ((bits >> bit) & 1U);
		}
		vcd << ' ' << signals[index++].id << '\n';
	}
	vcd << "$end\n";
}

void process_outputs()
{
	for (int i = 0; i < IO_OUTPUT_COUNT; ++i) {
		const bool state = io_get_output(static_cast<io_output>(i));
		if (state != recorded_output_values[i]) {
			recorded_output_values[i] = state;
			write_scalar(IO_INPUT_COUNT + i, state, current_time);
		}
	}
}

[[noreturn]] void fail_from_c(const char *message)
{
	std::cerr << "Host IO/parameter stub error: " << message << '\n';
	std::exit(EXIT_FAILURE);
}

} // namespace

extern "C" int32_t params_get(uint8_t id)
{
	if (id >= PARAM_COUNT) {
		fail_from_c("logic requested an invalid parameter ID");
	}
	return parameter_values[id];
}

extern "C" void params_set(uint8_t id, int32_t value)
{
	if (id >= PARAM_COUNT) {
		fail_from_c("invalid parameter ID");
	}
	parameter_values[id] = value;
}

extern "C" bool io_get_input(enum io_input input)
{
	if (input < 0 || input >= IO_INPUT_COUNT) {
		fail_from_c("invalid input ID");
	}
	return input_values[input];
}

extern "C" bool io_get_output(enum io_output output)
{
	if (output < 0 || output >= IO_OUTPUT_COUNT) {
		fail_from_c("invalid output ID");
	}
	return output_values[output];
}

extern "C" int io_set_output(enum io_output output, bool on)
{
	if (output < 0 || output >= IO_OUTPUT_COUNT) {
		fail_from_c("invalid output ID");
	}
	output_values[output] = on;
	return 0;
}

void param(int parameter_id, int value)
{
	if (parameter_id < 0 || parameter_id >= PARAM_COUNT) {
		throw std::out_of_range("invalid parameter ID");
	}
	parameter_values[parameter_id] = value;
	write_parameter(IO_INPUT_COUNT + IO_OUTPUT_COUNT + parameter_id,
			value, current_time);
}

void force_work(int hours)
{
	constexpr int parameter_id = PARAM_WYMUSZONA_PRACA;
	const int old_value = parameter_values[parameter_id];
	struct parameter forced_work = {};

	parameter_values[parameter_id] = hours;
	write_parameter(IO_INPUT_COUNT + IO_OUTPUT_COUNT + parameter_id,
			hours, current_time);

	forced_work.value = hours;
	param_write_wymuszona_praca(&forced_work, old_value);
	parameter_values[parameter_id] = forced_work.value;
	write_parameter(IO_INPUT_COUNT + IO_OUTPUT_COUNT + parameter_id,
			forced_work.value, current_time);
}

void on(int input_id)
{
	if (input_id < 0 || input_id >= IO_INPUT_COUNT) {
		throw std::out_of_range("invalid input ID");
	}
	if (!input_values[input_id]) {
		input_values[input_id] = true;
		write_scalar(input_id, true, current_time);
	}
}

void off(int input_id)
{
	if (input_id < 0 || input_id >= IO_INPUT_COUNT) {
		throw std::out_of_range("invalid input ID");
	}
	if (input_values[input_id]) {
		input_values[input_id] = false;
		write_scalar(input_id, false, current_time);
	}
}

void delay(double seconds)
{
	if (!std::isfinite(seconds) || seconds < 0) {
		throw std::invalid_argument("delay must be a finite, non-negative number");
	}
	const double max_ticks = static_cast<double>(INT32_MAX - current_time);
	if (seconds > max_ticks / 10.0) {
		throw std::overflow_error("delay exceeds the supported simulation time");
	}
	const long long ticks = std::llround(seconds * 10.0);
	for (long long i = 0; i < ticks; ++i) {
		procesuj(current_time);
		process_outputs();
		++current_time;
	}
}

void jump(double seconds)
{
	if (!std::isfinite(seconds) || seconds < 0) {
		throw std::invalid_argument("jump target must be a finite, non-negative number");
	}
	const double target_ticks = seconds * 10.0;
	if (target_ticks > INT32_MAX) {
		throw std::overflow_error("jump target exceeds the supported simulation time");
	}
	const int target_time = static_cast<int>(std::llround(target_ticks));
	if (target_time < current_time) {
		throw std::invalid_argument("jump target cannot be earlier than current time");
	}
	while (current_time < target_time) {
		procesuj(current_time);
		process_outputs();
		++current_time;
	}
}

double time()
{
	return current_time / 10.0;
}

void test();

int main(int argc, char **argv)
{
	if (argc != 2) {
		std::cerr << "usage: " << argv[0] << " <output.vcd>\n";
		return 2;
	}

	try {
		initialize_vcd(argv[1]);
		test();
		write_time(current_time);
		vcd.flush();
		if (!vcd) {
			throw std::runtime_error(std::string("failed writing VCD file: ") + argv[1]);
		}
		std::cout << "Wrote " << argv[1] << '\n';
	} catch (const std::exception &error) {
		std::cerr << "Test failed: " << error.what() << '\n';
		return 1;
	}
	return 0;
}
